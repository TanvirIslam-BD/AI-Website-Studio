export function stockImages(topic: StockTopic | string, count = 6): string[] {
  const key = (topic in STOCK ? topic : 'abstract') as StockTopic;
  const pool = STOCK[key];
  return Array.from({ length: count }, (_, i) => u(pool[i % pool.length]));
}

export function stockImage(topic: StockTopic | string, index = 0): string {
  return stockImages(topic, index + 1)[index];
}

